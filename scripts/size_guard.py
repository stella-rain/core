#!/usr/bin/env python3
"""Warns on a hand-written .rs file past 1,500 lines; never fails (tasks DS-0523).

Reads every tracked `.rs` file outside `src/sim_v1/` (the frozen rules). A file past LIMIT lines is
a `::warning`; a test-only file past it is listed as a `::notice` and exempt. Generated files are
skipped. Read-only: it opens files for reading and always exits 0, so CI only shows the warning.
"""

import os
import re
import subprocess
import sys

LIMIT = 1500
SKIPPED_PREFIX = "src/sim_v1/"
SPLIT_HINT = "split it by area (epic stella-rain/tasks#562)"
GENERATED_MARKERS = ("@generated", "do not edit")
DECLARATION_FILES = ("mod.rs", "lib.rs", "main.rs")


def is_generated(lines):
    """One of the first 10 lines holds a marker or starts (after `//` or `//!`) with `generated by`."""
    for line in lines[:10]:
        low = line.lower()
        if any(marker in low for marker in GENERATED_MARKERS):
            return True
        if re.sub(r"^\s*//!?\s*", "", low).startswith("generated by"):
            return True
    return False


def declared_cfg_test(root, path):
    """True when the parent module declares this file as `mod <name>;` right under `#[cfg(test)]`."""
    folder, name = os.path.split(path)
    stem = name[:-3]
    candidates = [os.path.join(folder, f) for f in DECLARATION_FILES]
    candidates.append(folder + ".rs")
    decl = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+" + re.escape(stem) + r"\s*;")
    for parent in candidates:
        try:
            with open(os.path.join(root, parent), encoding="utf-8") as f:
                lines = f.read().splitlines()
        except (OSError, UnicodeDecodeError):
            continue
        for i, line in enumerate(lines):
            if not decl.match(line):
                continue
            j = i - 1
            while j >= 0 and lines[j].strip().startswith("#["):
                if lines[j].strip() == "#[cfg(test)]":
                    return True
                j -= 1
    return False


def is_test_only(root, path):
    parts = path.split("/")
    name = parts[-1]
    return ("tests" in parts[:-1] or name == "tests.rs" or name.endswith("_tests.rs")
            or declared_cfg_test(root, path))


def scan(root, paths, with_notices=False):
    """Returns (warnings, exempt) as lists of (path, lines); with_notices adds a third list of
    messages for files that could not be read."""
    warnings, exempt, notices = [], [], []
    for path in paths:
        if not path.endswith(".rs") or path.startswith(SKIPPED_PREFIX):
            continue
        try:
            with open(os.path.join(root, path), encoding="utf-8", newline="") as f:
                text = f.read()
        except (OSError, UnicodeDecodeError) as err:
            notices.append(f"::notice file={path},title=Size guard skipped a file::{path} "
                           f"could not be read ({err.__class__.__name__})")
            continue
        lines = text.splitlines()
        if is_generated(lines):
            continue
        if len(lines) > LIMIT:
            (exempt if is_test_only(root, path) else warnings).append((path, len(lines)))
    return (warnings, exempt, notices) if with_notices else (warnings, exempt)


def render(warnings, exempt):
    def order(entries):
        return sorted(entries, key=lambda e: (-e[1], e[0]))

    out = [f"::warning file={p},title=File past {LIMIT} lines::{p} has {n} lines "
           f"(limit {LIMIT}): {SPLIT_HINT}" for p, n in order(warnings)]
    out += [f"::notice file={p},title=Test file past {LIMIT} lines (exempt)::{p} has {n} lines "
            "(test-only, exempt)" for p, n in order(exempt)]
    out.append(f"size guard: {len(warnings)} warning(s), {len(exempt)} exempt test file(s), "
               f"limit {LIMIT}, {SKIPPED_PREFIX} skipped")
    return out


def tracked_rs(root):
    result = subprocess.run(["git", "ls-files", "-z", "*.rs"], cwd=root, capture_output=True,
                            check=True)
    return [p for p in result.stdout.decode("utf-8").split("\0") if p]


def main():
    root = os.getcwd()
    try:
        paths = tracked_rs(root)
    except (OSError, subprocess.CalledProcessError):
        print("::notice title=Size guard skipped::git ls-files failed; no files checked")
        return 0
    warnings, exempt, notices = scan(root, paths, with_notices=True)
    for line in notices + render(warnings, exempt):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
