#!/usr/bin/env python3
"""The ADR IDs core may cite, and the scan that keeps every citation real.

`adr_ids.txt` lists, one per line, an ADR ID and the number of its Decision points. It is written
from a clone of the app repository (`write APP_DIR`) and compared with one (`check APP_DIR`);
`test_adr_ids.py` scans the tracked text of this repository against it, offline.

The set in force is selected by the first temporary number of each area (FIRST_NUMBER). The table
is deleted when the temporary numbers are replaced by the final ones.
"""

import os
import re
import subprocess
import sys

LIST_NAME = "adr_ids.txt"
HEADER = ("# Generated by scripts/adr_ids.py from the app repository's architecture records; "
          "IDs and counts only.")

# First temporary number of each area; every ADR from there up is in the set.
FIRST_NUMBER = {"SIM": 15, "CONT": 11, "REPL": 12, "BRDG": 10, "SAVE": 11, "REL": 10, "PLAT": 5,
                "SVC": 7, "PROC": 4}

# Not read by the scan: test inputs and recordings that carry old text on purpose, the list, and
# the scan's own source and test, which quote the forms they look for.
EXCLUDED_PREFIXES = ("tests/corpus/", "tests/fixtures/", "scripts/adr_ids.txt", "scripts/adr_ids.py",
                     "scripts/test_adr_ids.py")

# Paths the scan does not read yet: the files that only Kade merges. Emptied by the follow-up
# change that moves their citations.
PENDING = (".claude/", ".agents/", ".github/", "AGENTS.md", "CLAUDE.md", "benches/accepted.toml",
           "benches/budgets.toml")

# `ADR-SIM-19`, `ADR-SIM-19 point 4`, `ADR-SIM-19 points 4 and 5`; the same grammar as the app's
# own checker. A legacy number is `ADR-020` or `ADR 020`.
ID_RE = re.compile(r"ADR-([A-Z]+-[0-9]+)\b")
LEGACY_RE = re.compile(r"\bADR[- ][0-9]{3}\b")
POINT_NUMS = r"(\d+(?:\s*(?:,|and|to|-|–)\s*\d+)*)"
POINT_FORWARD_RE = re.compile(
    r"ADR-([A-Z]+-\d+)[\s,()]*(?:points?|decisions?)\s+" + POINT_NUMS, re.IGNORECASE)
POINT_BACK_RE = re.compile(
    r"\bpoints?\s+" + POINT_NUMS + r"\s+(?:of|in)\s+ADR-([A-Z]+-\d+)\b", re.IGNORECASE)
# core has neither folder: a path into them is a citation of the app's documents.
DOCUMENT_RE = re.compile(r"\bdocs/(?:design|architecture)/[\w./-]+\.md")
COMMENT_PREFIX_RE = re.compile(r"^\s*(?:///|//!|//|#|;|<!--|\*)\s?")


def point_numbers(text):
    """Numbers named by `1`, `1, 3 and 5` or `1 to 3`; a range expands."""
    parts = re.split(r"\s*(,|and|to|-|–)\s*", text.strip())
    numbers, i = [], 0
    while i < len(parts):
        n = int(parts[i])
        if i + 2 < len(parts) and parts[i + 1] in ("to", "-", "–"):
            numbers.extend(range(n, int(parts[i + 2]) + 1))
            i += 4
        else:
            numbers.append(n)
            i += 2
    return numbers


def parse_list(text):
    """`ADR-SIM-19 7` lines -> {"SIM-19": 7}."""
    ids = {}
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, count = line.split()
        ids[name.removeprefix("ADR-")] = int(count)
    return ids


def load_list(path):
    with open(path, encoding="utf-8") as f:
        return parse_list(f.read())


def decision_points(lines):
    """The largest N of the `N. ` lines at column 0 inside `## Decision`, or 0."""
    inside, top = False, 0
    for line in lines:
        if line.startswith("## "):
            inside = line.strip() == "## Decision"
            continue
        m = re.match(r"^(\d+)\. ", line) if inside else None
        if m:
            top = max(top, int(m.group(1)))
    return top


def read_app(app_dir):
    """{"SIM-19": 7, ...} for the ADRs of the set in force under APP_DIR/docs/adr."""
    root = os.path.join(app_dir, "docs", "adr")
    ids = {}
    for area, first in FIRST_NUMBER.items():
        folder = os.path.join(root, area.lower())
        if not os.path.isdir(folder):
            raise SystemExit(f"no ADR folder for {area}: {folder}")
        for name in sorted(os.listdir(folder)):
            m = re.match(r"^(\d{3})-.*\.md$", name)
            if not m or int(m.group(1)) < first:
                continue
            with open(os.path.join(folder, name), encoding="utf-8") as f:
                points = decision_points(f.read().splitlines())
            if points == 0:
                raise SystemExit(f"{os.path.join(folder, name)}: no Decision points")
            ids[f"{area}-{int(m.group(1))}"] = points
    return ids


def render(ids):
    def key(name):
        area, n = name.rsplit("-", 1)
        return (area, int(n))

    lines = [HEADER]
    lines += [f"ADR-{name} {ids[name]}" for name in sorted(ids, key=key)]
    return "\n".join(lines) + "\n"


def skipped(path):
    return path.startswith(EXCLUDED_PREFIXES) or path.startswith(PENDING)


def scan_text(path, text, ids):
    """Findings for one file: (path, line, kind, text). A citation wrapped onto the next comment
    line is joined to the line it starts on."""
    findings = []
    lines = text.split("\n")
    for i, line in enumerate(lines):
        joined = line
        if i + 1 < len(lines):
            nxt = COMMENT_PREFIX_RE.sub("", lines[i + 1], count=1)
            if COMMENT_PREFIX_RE.match(lines[i + 1]) and COMMENT_PREFIX_RE.match(line):
                joined = line + " " + nxt
        for m in LEGACY_RE.finditer(line):
            findings.append((path, i + 1, "legacy", m.group(0)))
        for m in ID_RE.finditer(line):
            if m.group(1) not in ids:
                findings.append((path, i + 1, "missing", m.group(0)))
        for m in DOCUMENT_RE.finditer(line):
            findings.append((path, i + 1, "document", m.group(0)))
        # point citations: only the matches that start on this line (the join is for the tail)
        for m in POINT_FORWARD_RE.finditer(joined):
            if m.start() >= len(line) or m.group(1) not in ids:
                continue
            for n in point_numbers(m.group(2)):
                if n > ids[m.group(1)] or n < 1:
                    findings.append((path, i + 1, "point", f"ADR-{m.group(1)} point {n}"))
        for m in POINT_BACK_RE.finditer(joined):
            if m.start() >= len(line) or m.group(2) not in ids:
                continue
            for n in point_numbers(m.group(1)):
                if n > ids[m.group(2)] or n < 1:
                    findings.append((path, i + 1, "point", f"ADR-{m.group(2)} point {n}"))
    return findings


def tracked_files(root):
    out = subprocess.run(["git", "-C", root, "ls-files", "-z"], check=True, capture_output=True)
    return [p for p in out.stdout.decode().split("\0") if p]


def scan_tree(root, ids, files=None):
    findings = []
    for path in files if files is not None else tracked_files(root):
        if skipped(path) or path.endswith("Cargo.lock"):
            continue
        try:
            with open(os.path.join(root, path), "rb") as f:
                data = f.read()
            text = data.decode("utf-8")
        except (UnicodeDecodeError, FileNotFoundError, IsADirectoryError):
            continue
        findings += scan_text(path, text, ids)
    return findings


def main(argv):
    if len(argv) not in (3, 4) or argv[1] not in ("write", "check"):
        print("usage: adr_ids.py write|check APP_DIR [LIST]", file=sys.stderr)
        return 2
    here = os.path.dirname(os.path.abspath(__file__))
    target = argv[3] if len(argv) == 4 else os.path.join(here, LIST_NAME)
    fresh = render(read_app(argv[2]))
    if argv[1] == "write":
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(fresh)
        return 0
    with open(target, encoding="utf-8") as f:
        if f.read() != fresh:
            print(f"{LIST_NAME} differs from the app records; run `adr_ids.py write {argv[2]}`",
                  file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
