"""Unit tests for scripts/size_guard.py: the warning for a hand-written .rs file past 1,500 lines."""

import os
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(__file__))

import size_guard

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(HERE, "size_guard.py")


def make(root, files):
    """Write each path with n lines of `// x`; a str value is written as given."""
    for path, body in files.items():
        full = os.path.join(root, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        text = body if isinstance(body, str) else "// x\n" * body
        with open(full, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def scan_files(files):
    with tempfile.TemporaryDirectory() as root:
        make(root, files)
        return size_guard.scan(root, sorted(files))


def padded(n, first=None, at=None, marker=None):
    """n lines; `first` replaces line 1, `marker` replaces line `at` (1-based)."""
    lines = ["// x"] * n
    if first:
        lines[0] = first
    if marker:
        lines[at - 1] = marker
    return "\n".join(lines) + "\n"


class Counting(unittest.TestCase):
    def test_the_limit_is_1500(self):
        self.assertEqual(size_guard.LIMIT, 1500)

    def test_exactly_the_limit_is_not_warned(self):
        self.assertEqual(scan_files({"src/a.rs": 1500}), ([], []))

    def test_one_past_the_limit_is_warned(self):
        self.assertEqual(scan_files({"src/a.rs": 1501}), ([("src/a.rs", 1501)], []))

    def test_a_last_line_without_newline_counts(self):
        text = "// x\n" * 1500 + "// last"
        self.assertEqual(scan_files({"src/a.rs": text}), ([("src/a.rs", 1501)], []))

    def test_an_empty_file_counts_zero(self):
        self.assertEqual(scan_files({"src/a.rs": ""}), ([], []))


class Scope(unittest.TestCase):
    def test_sim_v1_is_skipped(self):
        self.assertEqual(scan_files({"src/sim_v1/big.rs": 3000}), ([], []))

    def test_sim_is_not_skipped(self):
        self.assertEqual(scan_files({"src/sim/big.rs": 3000}), ([("src/sim/big.rs", 3000)], []))

    def test_generated_files_are_in_neither_list(self):
        files = {
            "src/g1.rs": padded(2000, first="// @generated"),
            "src/g2.rs": padded(2000, at=5, marker="// DO NOT EDIT"),
            "src/g3.rs": padded(2000, first="//! Generated by xtask"),
        }
        self.assertEqual(scan_files(files), ([], []))

    def test_a_marker_on_line_11_is_not_a_marker(self):
        files = {"src/g.rs": padded(2000, at=11, marker="// @generated")}
        self.assertEqual(scan_files(files), ([("src/g.rs", 2000)], []))


class TestOnly(unittest.TestCase):
    def test_by_path(self):
        paths = ["tests/x.rs", "tests/common/y.rs", "fuzz/tests/smoke.rs", "src/a_tests.rs",
                 "src/tests.rs"]
        warnings, exempt = scan_files({p: 1600 for p in paths})
        self.assertEqual(warnings, [])
        self.assertEqual(sorted(p for p, _ in exempt), sorted(paths))

    def test_declared_under_cfg_test(self):
        files = {"src/m/mod.rs": "#[cfg(test)]\nmod before;\n", "src/m/before.rs": 1600}
        self.assertEqual(scan_files(files), ([], [("src/m/before.rs", 1600)]))

    def test_declared_without_cfg_test_is_a_warning(self):
        files = {"src/m/mod.rs": "mod before;\n", "src/m/before.rs": 1600}
        self.assertEqual(scan_files(files), ([("src/m/before.rs", 1600)], []))

    def test_stacked_attributes_and_visibility(self):
        files = {"src/m/mod.rs": "#[cfg(test)]\n#[allow(dead_code)]\npub(crate) mod before;\n",
                 "src/m/before.rs": 1600}
        self.assertEqual(scan_files(files), ([], [("src/m/before.rs", 1600)]))

    def test_declared_in_the_2018_root_beside_its_folder(self):
        files = {"src/pack.rs": "#[cfg(test)]\nmod t;\n", "src/pack/t.rs": 1600}
        self.assertEqual(scan_files(files), ([], [("src/pack/t.rs", 1600)]))

    def test_inline_test_module_next_to_live_code_counts_whole(self):
        text = "fn live() {}\n" + "// x\n" * 1598 + "#[cfg(test)]\nmod tests {\n}\n"
        warnings, exempt = scan_files({"src/inline.rs": text})
        self.assertEqual(len(warnings), 1)
        self.assertEqual(exempt, [])

    def test_a_test_file_under_the_line_is_in_neither_list(self):
        self.assertEqual(scan_files({"tests/small.rs": 1499}), ([], []))


class Render(unittest.TestCase):
    def test_warning_line_is_exact(self):
        lines = size_guard.render([("src/a.rs", 1600)], [])
        self.assertEqual(
            lines[0],
            "::warning file=src/a.rs,title=File past 1500 lines::src/a.rs has 1600 lines "
            "(limit 1500): split it by area (epic stella-rain/tasks#562)")

    def test_exempt_line_is_a_notice(self):
        lines = size_guard.render([], [("tests/b.rs", 1700)])
        self.assertEqual(
            lines[0],
            "::notice file=tests/b.rs,title=Test file past 1500 lines (exempt)::tests/b.rs has "
            "1700 lines (test-only, exempt)")

    def test_order_is_count_descending_then_path_and_summary_last(self):
        lines = size_guard.render([("src/b.rs", 1600), ("src/a.rs", 1600), ("src/c.rs", 1700)],
                                  [("tests/y.rs", 1600), ("tests/x.rs", 1900)])
        files = [line.split("file=")[1].split(",")[0] for line in lines[:-1]]
        self.assertEqual(files[:3], ["src/c.rs", "src/a.rs", "src/b.rs"])
        self.assertEqual(files[3:], ["tests/x.rs", "tests/y.rs"])
        self.assertEqual(lines[-1], "size guard: 3 warning(s), 2 exempt test file(s), limit 1500, "
                                    "src/sim_v1/ skipped")


class Run(unittest.TestCase):
    def run_script(self, cwd):
        return subprocess.run([sys.executable, SCRIPT], cwd=cwd, capture_output=True, text=True)

    def test_exit_zero_with_a_warning_and_a_notice_and_nothing_written(self):
        with tempfile.TemporaryDirectory() as root:
            subprocess.run(["git", "init", "-q"], cwd=root, check=True)
            make(root, {"src/a.rs": 3000, "tests/b.rs": 3000})
            subprocess.run(["git", "add", "-A"], cwd=root, check=True)
            before = subprocess.run(["git", "status", "--porcelain"], cwd=root,
                                    capture_output=True, text=True).stdout
            result = self.run_script(root)
            after = subprocess.run(["git", "status", "--porcelain"], cwd=root,
                                   capture_output=True, text=True).stdout
        self.assertEqual(result.returncode, 0)
        self.assertEqual(result.stdout.count("::warning file=src/a.rs"), 1)
        self.assertEqual(result.stdout.count("::notice file=tests/b.rs"), 1)
        self.assertEqual(before, after)
        self.assertEqual(sorted(line[3:] for line in after.splitlines()),
                         ["src/a.rs", "tests/b.rs"])

    def test_exit_zero_outside_a_git_repository(self):
        with tempfile.TemporaryDirectory() as root:
            result = self.run_script(root)
        self.assertEqual(result.returncode, 0)
        self.assertIn("::notice", result.stdout)

    def test_a_missing_listed_path_does_not_raise(self):
        with tempfile.TemporaryDirectory() as root:
            warnings, exempt, notices = size_guard.scan(root, ["src/gone.rs"], with_notices=True)
        self.assertEqual((warnings, exempt), ([], []))
        self.assertEqual(len(notices), 1)


if __name__ == "__main__":
    unittest.main()
